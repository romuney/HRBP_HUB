/* ============================================================
   HRBP HUB · Proteus (Superset) · метрики датасета `hrbp_hub`
   ------------------------------------------------------------
   Определяются один раз на датасете и переиспользуются всеми чартами.
   Руками в чартах эти формулы не пишутся: как только их станет две
   версии, два графика об одном и том же покажут разные числа.

   ОБЩЕЕ УСЛОВИЕ КОРРЕКТНОСТИ
     В группировке или в фильтре запроса всегда есть metric_id,
     и всегда зафиксирован ровно один scope_unit_id.
     Первое — потому что метрики нельзя складывать между собой,
     второе — потому что строка листа повторена по всем его предкам.
   ============================================================ */


-- ────────────────────────────────────────────────────────────
-- Значение
-- Доли и средние — отношение сумм, а не среднее отношений: отдел
-- из 6 человек не должен весить как отдел из 600. Абсолютные метрики
-- (численность) складываются.
-- ────────────────────────────────────────────────────────────
if(min(is_ratio) = 1,
   min(out_scale) * sum(value_num) / nullIf(sum(value_den), 0),
   sum(value_num))


-- ────────────────────────────────────────────────────────────
-- Δ к прошлому периоду  (месяц или неделя — по grain чарта)
-- Считается из лагов, лежащих в той же строке: числитель и знаменатель
-- прошлого периода так же аддитивны, поэтому дельта остаётся верной
-- под любым набором фильтров и на любом уровне дерева.
-- ────────────────────────────────────────────────────────────
if(min(is_ratio) = 1,
   min(out_scale) * (sum(value_num)  / nullIf(sum(value_den), 0)
                   - sum(num_prev_p) / nullIf(sum(den_prev_p), 0)),
   sum(value_num) - sum(num_prev_p))


-- ────────────────────────────────────────────────────────────
-- Δ год к году
-- ────────────────────────────────────────────────────────────
if(min(is_ratio) = 1,
   min(out_scale) * (sum(value_num)  / nullIf(sum(value_den), 0)
                   - sum(num_prev_y) / nullIf(sum(den_prev_y), 0)),
   sum(value_num) - sum(num_prev_y))


-- ────────────────────────────────────────────────────────────
-- База сравнения (вся компания под теми же разрезами)
-- ВНИМАНИЕ: bench_* размножены джойном по строкам, sum() их задвоит.
-- Только max/any и только когда в группировке есть период.
-- ────────────────────────────────────────────────────────────
if(min(is_ratio) = 1,
   min(out_scale) * max(bench_num) / nullIf(max(bench_den), 0),
   max(bench_num))


-- ────────────────────────────────────────────────────────────
-- Цель юнита отчёта / цель строки таблицы
-- Тот же случай размножения: агрегат — max, и в группировке обязаны
-- быть юнит и метрика.
-- ────────────────────────────────────────────────────────────
max(target_scope)
max(target_child)


-- ────────────────────────────────────────────────────────────
-- Ориентир — единая развилка на весь отчёт
-- Есть цель — сравниваемся ТОЛЬКО с ней, база рядом не показывается.
-- Абсолютные метрики с базой не сравниваются: 212 человек против 2 968 —
-- это масштаб, а не оценка.
-- ────────────────────────────────────────────────────────────
coalesce(max(target_child),
         if(min(is_ratio) = 1 and min(metric_better) != 'flat',
            min(out_scale) * max(bench_num) / nullIf(max(bench_den), 0),
            null))


-- ────────────────────────────────────────────────────────────
-- Отклонение к ориентиру, в сторону «лучше»
-- Это то, что красит светофор. Порог статический ±5% (мёртвая зона
-- макета), а ориентир у каждой строки свой — цель или база. Поэтому
-- в conditional formatting уходит НОРМИРОВАННОЕ отклонение, а не само
-- значение метрики: иначе пороги пришлось бы задавать для каждой строки.
--   > +5%  — зелёный,  −5% … +5% — серый,  < −5% — красный
-- Вариантов метрики два — с target_child (таблица «Команды») и с
-- target_scope (сводка One-Pager). Отличаются только этим именем.
-- ────────────────────────────────────────────────────────────
multiIf(
    min(metric_better) = 'flat', null,                  -- «больше» не значит «лучше»
    coalesce(max(target_child),
             if(min(is_ratio) = 1,
                min(out_scale) * max(bench_num) / nullIf(max(bench_den), 0),
                null)) is null, null,                   -- ориентира нет
    (if(min(metric_better) = 'higher', 1, -1)
      * ( if(min(is_ratio) = 1,
             min(out_scale) * sum(value_num) / nullIf(sum(value_den), 0),
             sum(value_num))
        - coalesce(max(target_child),
                   min(out_scale) * max(bench_num) / nullIf(max(bench_den), 0)) )
      / nullIf(abs(coalesce(max(target_child),
                            min(out_scale) * max(bench_num) / nullIf(max(bench_den), 0))), 0)))


-- ────────────────────────────────────────────────────────────
-- Численность популяции
-- В макете это подпись «N чел» под названием юнита; в Superset ячейка —
-- одно число, поэтому численность становится обычной колонкой сводной.
-- Метрика ниже работает, только пока строки headcount не выключены
-- фильтром «Метрики для отображения», — то есть в чартах, где этот
-- фильтр не в области видимости (например, в шапке-счётчике).
-- ────────────────────────────────────────────────────────────
sumIf(value_num, metric_id = 'headcount')
